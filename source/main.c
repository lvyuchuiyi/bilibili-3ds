static int font_idx(char ch){
if(ch>='0'&&ch<='9')return ch-'0';
if(ch>='A'&&ch<='Z')return ch-'A'+10;
if(ch==' ')return 36; if(ch==':')return 37; if(ch=='-')return 38;
return 36; /* unknown -> space */
}

static void draw_char(int x,int y,char ch,u32 col){
int idx=font_idx(ch);
for(int r=0;r<8;r++){unsigned char bits=font[idx][r];
for(int c=0;c<8;c++){if(bits&(0x80>>c))C2D_DrawRectSolid(x+c,y+r,0.5f,1,1,col);}}
}

static void draw_str(int x,int y,u32 col,const char*s){
while(*s){draw_char(x,y,*s,col);x+=9;s++;}
}

