static int f_idx(char c){
if(c>='0'&&c<='9')return c-'0';
if(c>='A'&&c<='Z')return c-'A'+10;
if(c>='a'&&c<='z')return c-'a'+36;
if(c==' ')return 62;if(c==':')return 63;if(c=='-')return 64;
return 62;
}
static void dch(int x,int y,char ch,u32 col){
int idx=f_idx(ch);
for(int r=0;r<8;r++){unsigned char bits=font[idx][r];
for(int c=0;c<8;c++){if(bits&(0x80>>c))C2D_DrawRectSolid(x+c,y+r,0.5f,1,1,col);}}
}
static void dstr(int x,int y,u32 col,const char*s){while(*s){dch(x,y,*s,col);x+=9;s++;}}

